"""Reproducible Markdown report: provenance, join integrity, recounts and reconciliation."""
import json

from experiment_context_markdown_detail import (cell, render_faction_details,
                                                render_march_evidence)


def render_markdown(model):
    lines = []
    add = lines.append
    inputs = model["inputs"]
    add("# Experiment context analysis — %s" % ", ".join(model["run_ids"] or ["unknown run"]))
    add("")
    add("Offline reconstruction of the stored run evidence. Generated by "
        "`tools/experiment_context_analysis.py` %s; no provider call was made and no scene was "
        "saved. Missing evidence is printed as unknown with known/missing counts."
        % model["tool"]["version"])
    add("")
    add("Reproduce:")
    add("")
    add("```")
    add("python tools/experiment_context_analysis.py \\")
    add("    --run %s \\" % (inputs.get("run", {}).get("path") or "<run.jsonl>"))
    add("    --exchanges %s \\" % (inputs.get("exchanges", {}).get("path")
                                  or "<exchanges.ndjson>"))
    add("    --summary %s \\" % (inputs.get("summary", {}).get("path") or "<summary.json>"))
    add("    --out-json <analysis.json> --out-md <REPORT.md>")
    add("```")
    add("")
    _render_inputs(inputs, add)
    _render_join(model, add)
    _render_geometry(model["geometry"], add)
    _render_verification(model["verification"], add)
    _render_reconciliation(model["reconciliation"], add)
    render_faction_details(model, add)
    render_march_evidence(model, add)
    _render_gaps(model["evidence_gaps"], add)
    return "\n".join(lines)


def _render_inputs(inputs, add):
    add("## Inputs")
    add("")
    add("| input | path (display) | sha256 | records | status |")
    add("| --- | --- | --- | --- | --- |")
    for key in ("run", "exchanges", "summary"):
        item = inputs.get(key) or {}
        add("| %s | `%s` | `%s` | %s | %s |" % (
            key, item.get("path") or "not supplied", (item.get("sha256") or "n/a")[:12],
            item.get("lines") if item.get("lines") is not None else "n/a",
            item.get("status") or "loaded"))
    add("")
    add("Hashes are taken from the absolute input paths, so they do not depend on the working "
        "directory the tool was started from.")
    add("")


def _render_join(model, add):
    join_data = model["join"]
    add("## Join integrity")
    add("")
    add("- Composite key: `%s`." % " + ".join(join_data["composite_key"]))
    add("- Legacy `exchange_id` (`run:N`) is **not** used as a join key: it repeats across seats "
        "and seasons.")
    add("- Joined requests: %d (usable %d, degraded %d, excluded %d)."
        % (join_data["joined_requests"], join_data["usable_requests"],
           join_data["degraded_requests"], join_data["excluded_requests"]))
    add("- `turn_end` sidecar records: %d; `experiment_config` records: %d."
        % (join_data["turn_end_sidecars"], join_data["experiment_config_records"]))
    if join_data.get("experiment_config_lines"):
        add("- `experiment_config` lines: %s."
            % ", ".join("`%s`" % cite for cite in join_data["experiment_config_lines"]))
    if join_data.get("summary_scope_ambiguous"):
        add("- Summary coverage is **ambiguous**: it spans several run ids and its turns and "
            "scoreboards are keyed by seat and season only, so they are not used.")
    counts = model["diagnostics"]["counts"]
    add("- Diagnostics: %s." % (", ".join("%s=%d" % item for item in counts.items())
                                if counts else "none"))
    for item in model["diagnostics"]["items"]:
        add("  - `%s` %s" % (item.get("kind"),
                             json.dumps({k: v for k, v in item.items() if k != "kind"},
                                        sort_keys=True)))
    add("")


def _render_geometry(geometry, add):
    add("## Scenario geometry")
    add("")
    add("- Scenario: `%s`; status: %s." % (geometry.get("scenario_id"), geometry.get("status")))
    add("- Metric: %s." % geometry.get("metric"))
    if geometry.get("centre"):
        add("- Declared centre: %s — %s." % (tuple(geometry["centre"]),
                                            geometry.get("centre_label")))
    add("- Map source: `%s`." % (geometry.get("map_source") or "not available"))
    add("- This classification is geometry only. It is not an intent label and not evidence that "
        "any seat could see the neutral objective.")
    add("")


def _render_verification(verification, add):
    add("## Independent recount of the prior notes")
    add("")
    add("| claim | recount |")
    add("| --- | --- |")
    add("| Shu faction present in this run | %s |" % cell(verification["shu_faction_present"]))
    add("| accepted Shu marches in the raw run | %s |" % cell(verification["shu_accepted_marches"]))
    add("| summary last-command fidelity | %s |"
        % ", ".join("%s: %d" % item
                    for item in verification["summary_last_command_fidelity_counts"].items()))
    add("| turns whose summary last command cannot be compared | %d |"
        % verification["turns_with_unknown_summary_last_command"])
    add("| accepted marches that are not the summary's last command | %d of %d |"
        % (verification["accepted_marches_not_the_summary_last_command"],
           verification["accepted_marches_total"]))
    add("| research rules offered in any prompt | %s |"
        % cell(verification["research_rules_offered_in_any_prompt"]))
    add("| inquiry tools offered | %s |" % cell(verification["inquiry_tools_offered_in_any_prompt"]))
    add("| private note offered | %s |" % cell(verification["note_tool_offered_in_any_prompt"]))
    add("| inquiry replies / note replies / confirmed note saves / research choices | %d / %d / "
        "%d / %d |" % (verification["inquiry_replies"], verification["note_replies"],
                       verification["notes_saved_confirmed"], verification["research_choices"]))
    add("| research choices whose line was offered in their own request | %s |"
        % cell(verification["research_choices_offered_in_their_own_request"]))
    add("| every march destination listed in the displayed options | %s |"
        % cell(verification["all_march_destinations_displayed"]))
    add("| order types offered in the first Shu request | %s |"
        % cell(verification["first_shu_request_options"]))
    add("")
    if not verification["shu_faction_present"]:
        add("No Shu faction appears in this run, so every Shu-specific value is unknown rather "
            "than zero.")
        add("")
    for index, march in enumerate(verification["first_shu_marches"] or [], 1):
        add("%d. First Shu turn march %d: `%s` %s -> %s; destination displayed: %s; geometry "
            "relation: %s; source %s."
            % (index, index, march["army_id"], march["origin"], march["destination"],
               cell(march["destination_in_displayed_options"]), cell(march["geometry_relation"]),
               ", ".join("`%s`" % cite for cite in march["sources"].values())))
        if index == 1 and march["displayed_options"]:
            add("   - displayed options immediately before the order: %s; unlisted (truncated): "
                "%s." % ("; ".join(march["displayed_options"]),
                         cell(march["unlisted_option_count"])))
    if verification["first_shu_marches"]:
        add("")


def _render_reconciliation(reconciliation, add):
    add("## Raw run vs spectator summary")
    add("")
    add("- Summary present: %s; scope ambiguous: %s."
        % (cell(reconciliation["summary_present"]),
           cell(reconciliation["summary_scope_ambiguous"])))
    add("- Summary declared totals: %s; raw totals: %s."
        % (json.dumps(reconciliation["summary_declared_totals"], sort_keys=True),
           json.dumps(reconciliation["raw_totals"], sort_keys=True)))
    if not reconciliation["totals_compared"]:
        add("- Summary totals not compared: totals missing or run scope ambiguous.")
    elif reconciliation["discrepancies"]:
        for item in reconciliation["discrepancies"]:
            add("- Count discrepancy: `%s` summary=%s raw=%s."
                % (item["field"], item["summary"], item["raw"]))
    else:
        add("- No request/acceptance/rejection count discrepancy.")
    fidelity = reconciliation["summary_last_command_fidelity"]
    add("- Last-command fidelity (summary's one stored command vs the turn's last accepted "
        "order): %s." % ", ".join("%s: %d" % item for item in fidelity["result_counts"].items()))
    for row in fidelity["turns"]:
        add("  - %s season %s: summary `%s` (%s) vs raw last `%s` (%s): %s."
            % (row["seat_id"], row["season"], cell(row["summary_type"]),
               cell(row["summary_action_id"]), cell(row["raw_last_accepted_type"]),
               cell(row["raw_last_accepted_action_id"]), row["result"]))
    add("- %s" % fidelity["explanation"])
    add("- %s" % reconciliation["note"])
    add("")


def _render_gaps(gaps, add):
    add("## Evidence gaps")
    add("")
    if gaps:
        for gap in gaps:
            add("- %s" % gap)
    else:
        add("- None identified.")
    add("")
    add("## Redaction")
    add("")
    add("Only whitelisted fields are read: identity, acceptance, command, displayed options, "
        "seat-visible observation facts, token counts and the model's own `reason`/`summary`. "
        "Provider `raw_body`, `content_text`, `reasoning_content`/CoT and `error_detail` are never "
        "copied, and every emitted string is scrubbed for credential-looking material.")
    add("")
